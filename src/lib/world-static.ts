export function staticEvents(): WorldEvent[] {
  const now = new Date().toISOString();
  const out: WorldEvent[] = [];
  for (const [layer, points] of Object.entries(DATA) as [LayerId, P[]][]) {
    points.forEach(([name, lon, lat, detail], i) => {
      out.push({
        id: `s-${layer}-${i}`,
        title: name,
        layer,
        lon,
        lat,
        time: now,
        ...(detail ? { detail } : {}),
      });
    });
  }
  return out;
}
